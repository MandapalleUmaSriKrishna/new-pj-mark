export interface UniqueIndexSpec {
  fields: string[];
  /** Mongo partial-filter: enforce uniqueness only when all fields are present. */
  partial?: boolean;
}

export interface CollectionSpec {
  name: CollectionName;
  unique: UniqueIndexSpec[];
  indexes: string[][];
}

