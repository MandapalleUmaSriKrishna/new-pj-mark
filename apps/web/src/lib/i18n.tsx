const CATALOGUES: Record<string, Catalogue> = { en: EN, hi: HI, te: TE };

const STORAGE_KEY = 'kdc.locale';
const FALLBACK: Locale = DEFAULT_LOCALE;

export type TranslationVars = Record<string, string | number>;

export interface I18nValue {
  locale: Locale;
  dir: 'ltr' | 'rtl';
  setLocale: (locale: Locale) => void;
  t: (key: MessageKey, vars?: TranslationVars) => string;
  /** Format a date in the active locale. */
  dateFormat: Intl.DateTimeFormat;
  numberFormat: Intl.NumberFormat;
  /** Locales whose catalogue is complete; others fall back to English. */
  isFallback: boolean;
}

const I18nContext = createContext<I18nValue | null>(null);

function interpolate(message: string, vars?: TranslationVars): string {
  if (!vars) return message;
  return message.replace(/\{(\w+)\}/g, (whole, name: string) =>
    name in vars ? String(vars[name]) : whole,
  );
}

function detectLocale(): Locale {
  if (!isBrowser()) return FALLBACK;
  try {
    const stored = window.localStorage.getItem(STORAGE_KEY);
    if (stored && (SUPPORTED_LOCALES as readonly string[]).includes(stored))
      return stored as Locale;
  } catch {
    // Private browsing can throw on localStorage; fall through to the browser tag.
  }
  const browser = (window.navigator.language ?? 'en').slice(0, 2).toLowerCase();
  return (SUPPORTED_LOCALES as readonly string[]).includes(browser)
    ? (browser as Locale)
    : FALLBACK;
}

export function translate(locale: Locale, key: MessageKey, vars?: TranslationVars): string {
  const catalogue = CATALOGUES[locale] ?? EN;
  const message = catalogue[key] ?? EN[key] ?? key;
  return interpolate(message, vars);
}

export function I18nProvider({
  children,
  initialLocale,
}: {
  children: ReactNode;
  initialLocale?: Locale;
}) {
  const [locale, setLocaleState] = useState<Locale>(initialLocale ?? FALLBACK);

  useEffect(() => {
    if (initialLocale) setLocaleState(initialLocale);
    else setLocaleState(detectLocale());
  }, [initialLocale]);

  useEffect(() => {
    if (!isBrowser()) return;
    const root = document.documentElement;
    root.lang = locale;
    root.dir = locale === 'ar' ? 'rtl' : 'ltr';
    try {
      window.localStorage.setItem(STORAGE_KEY, locale);
    } catch {
      // Ignore storage failures; the choice still applies for this session.
    }
  }, [locale]);

  const setLocale = useCallback((next: Locale) => setLocaleState(next), []);
  const t = useCallback(
    (key: MessageKey, vars?: TranslationVars) => translate(locale, key, vars),
    [locale],
  );

  const value = useMemo<I18nValue>(
    () => ({
      locale,
      dir: locale === 'ar' ? 'rtl' : 'ltr',
      setLocale,
      t,
      dateFormat: new Intl.DateTimeFormat(locale === 'en' ? 'en-IN' : locale),
      numberFormat: new Intl.NumberFormat(locale === 'en' ? 'en-IN' : locale),
      isFallback: !CATALOGUES[locale],
    }),
    [locale, setLocale, t],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const context = useContext(I18nContext);
  if (context) return context;
  // Server components and tests render outside the provider: use English.
  return {
    locale: FALLBACK,
    dir: 'ltr',
    setLocale: () => undefined,
    t: (key: MessageKey, vars?: TranslationVars) => translate(FALLBACK, key, vars),
    dateFormat: new Intl.DateTimeFormat('en-IN'),
    numberFormat: new Intl.NumberFormat('en-IN'),
    isFallback: false,
  };
}

export const TRANSLATED_LOCALES: Locale[] = (Object.keys(CATALOGUES) as Locale[]).filter(
  (key) => key !== 'en',
);
