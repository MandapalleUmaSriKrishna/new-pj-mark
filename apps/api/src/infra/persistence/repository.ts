import type { BaseEntity } from '@kdc/shared';
import type { Filter, QueryOptions } from './filter';

export class DuplicateKeyError extends Error {
  constructor(
    readonly collection: string,
    readonly fields: string[],
    readonly value: unknown,
  ) {
    super(
      `Duplicate value for unique index [${fields.join(', ')}] in "${collection}": ${String(value)}`,
    );
    this.name = 'DuplicateKeyError';
  }
}

export class NotFoundError extends Error {
  constructor(
    readonly collection: string,
    readonly id: string,
  ) {
    super(`No document with id "${id}" in "${collection}"`);
    this.name = 'NotFoundError';
  }
}

/**
 * Payload accepted by `insert`.
 *
 * `id` is required because it is generated by the caller (so a document can be
 * referenced before it is persisted) and `createdAt` / `updatedAt` are optional
 * so imports can preserve an original issue date. Anything the caller omits is
 * stamped by the adapter.
 */
export type NewDoc<T extends BaseEntity> = Partial<T> & { id: string };

export interface Repository<T extends BaseEntity> {
  readonly name: string;
  find(filter?: Filter, options?: QueryOptions): Promise<T[]>;
  findOne(filter: Filter, options?: QueryOptions): Promise<T | null>;
  findById(id: string): Promise<T | null>;
  count(filter?: Filter): Promise<number>;
  exists(filter: Filter): Promise<boolean>;
  insert(data: NewDoc<T>): Promise<T>;
  insertMany(data: NewDoc<T>[]): Promise<T[]>;
  updateById(id: string, patch: Record<string, unknown>): Promise<T | null>;
  updateMany(filter: Filter, patch: Record<string, unknown>): Promise<number>;
  deleteById(id: string): Promise<boolean>;
  deleteMany(filter: Filter): Promise<number>;
  distinct(field: string, filter?: Filter): Promise<string[]>;
  /** Sums a numeric field across matching documents. */
  sum(field: string, filter?: Filter): Promise<number>;
}

export interface DataStore {
  readonly driver: 'mongo' | 'memory';
  repository<T extends BaseEntity>(name: CollectionName): Repository<T>;
  ping(): Promise<{ ok: boolean; detail?: string }>;
  close(): Promise<void>;
}

